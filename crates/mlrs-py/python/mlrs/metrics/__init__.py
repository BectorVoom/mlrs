"""``mlrs.metrics`` — sklearn-signature-faithful metrics.

Mirrors ``sklearn.metrics``' public function surface (scikit-learn 1.9): the
classification, regression, ranking and clustering scores, the pairwise
distance/kernel engine, and the scorer API. Every metric VALUE is computed in
Rust (``crates/mlrs-algos/src/metrics/``); these modules validate inputs with
sklearn's own messages, emit sklearn's warnings and shape the outputs.

Submodules, as in sklearn: :mod:`mlrs.metrics.cluster` and
:mod:`mlrs.metrics.pairwise`.

Not provided: the plotting ``*Display`` classes (they are matplotlib front
ends, not metrics — use sklearn's with the arrays these functions return).
Class labels must be integer (or boolean) valued.
"""

